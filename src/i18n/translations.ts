const translatedLanguageSet = new Set<string>(languages);

export function hasTranslations(locale: LocaleCode): locale is Lang {
  return translatedLanguageSet.has(locale);
}

export function getTranslationLanguage(locale: LocaleCode): Lang {
  return locale;
}

export function getLocaleFromUrl(url: URL): LocaleCode {
  return getLocaleFromPathname(url.pathname);
}

/** Backwards-compatible helper for code that requires a fully translated locale. */
export function getLangFromUrl(url: URL): Lang {
  return getTranslationLanguage(getLocaleFromUrl(url));
}

export function getTranslation(lang: LocaleCode, key: string): string {
  return t[lang]?.[key] || key;
}

/**
 * The park's own calendar year, always in Europe/Berlin.
 *
 * Build machines are not guaranteed to run in the park's timezone, so deriving
 * the year from local time would publish the wrong one for a few hours around
 * New Year.
 */
export function getParkYear(now: Date = new Date()): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Berlin',
    year: 'numeric',
  }).format(now);
}

/**
 * Fills `{placeholder}` slots in a translated string.
 *
 * Every consumer of a templated key must go through here — a raw
 * `getTranslation` call would ship the literal `{year}` to users and crawlers.
 * `verify-seo-build.ts` fails the build if an unresolved slot survives.
 */
export function fillTemplate(
  text: string,
  values: Record<string, string> = {},
): string {
  const merged: Record<string, string> = { year: getParkYear(), ...values };
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(merged, name) ? merged[name] : match,
  );
}

/** `getTranslation` with placeholder interpolation applied. */
export function getFilledTranslation(
  lang: LocaleCode,
  key: string,
  values: Record<string, string> = {},
): string {
  return fillTemplate(getTranslation(lang, key), values);
}
